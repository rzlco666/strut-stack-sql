//! `strut-stack-sql migrate --from-v1` (R2-07).
//!
//! Translates a V1 deployment configuration to the V2 file format: sources
//! and `deny_columns` carry over, process-wide options that V2 rejects in TOML
//! are reported with the CLI flag that replaces them, and the alias/binary
//! rename is stated once. The command never touches a database and never
//! overwrites a file unless `--write` is given.

use std::path::Path;

use anyhow::{bail, Context, Result};

const DEFAULT_OUT: &str = "strut-stack-sql.toml";

/// Top-level V1 keys that V2 moved to CLI flags.
const MOVED_TO_FLAGS: &[(&str, &str)] = &[
    ("max_rows", "--max-rows"),
    ("max_bytes", "--max-bytes"),
    ("query_timeout", "--query-timeout"),
    ("pool_size", "--pool-size"),
    ("connect_timeout", "--connect-timeout"),
    ("batch_concurrency", "--batch-concurrency"),
    ("batch_max_statements", "--batch-max-statements"),
    ("batch_timeout", "--batch-timeout"),
    ("batch_max_bytes", "--batch-max-bytes"),
    ("fail_fast", "--fail-fast"),
    (
        "write_mode",
        "--allow-writes / --allow-ddl / --allow-grants",
    ),
    ("http_auth", "--http-token / STRUT_STACK_SQL_HTTP_TOKENS"),
];

pub fn run(from_v1: bool, input: Option<&Path>, write: bool, out: Option<&Path>) -> Result<i32> {
    let input = input.unwrap_or_else(|| Path::new(DEFAULT_OUT));
    let text =
        std::fs::read_to_string(input).with_context(|| format!("reading {}", input.display()))?;
    let value: toml::Value =
        toml::from_str(&text).with_context(|| format!("parsing {}", input.display()))?;
    let table = value
        .as_table()
        .ok_or_else(|| anyhow::anyhow!("{} is not a TOML table", input.display()))?;

    let mut warnings: Vec<String> = Vec::new();
    if !from_v1 {
        warnings.push("input was not marked --from-v1: translating as if it were a V1 file".into());
    }

    let mut rendered = String::new();
    rendered.push_str("# Generated by `strut-stack-sql migrate --from-v1`.\n");
    rendered.push_str("# Review before use; V2 rejects unknown keys at startup.\n");
    rendered.push_str(
        "# The binary is `strut-stack-sql`: the `mcp-sql-rust` alias was removed in 2.0.0.\n",
    );
    rendered.push_str("# Principals/grants, approvals and table rules are V2 additions; see docs/CONFIGURATION.md.\n\n");

    if let Some(default_source) = table.get("default_source").and_then(|v| v.as_str()) {
        rendered.push_str(&format!("default_source = {default_source:?}\n\n"));
    }
    if let Some(deny) = table.get("deny_columns").and_then(|v| v.as_array()) {
        let cols: Vec<String> = deny
            .iter()
            .filter_map(|v| v.as_str())
            .map(|s| format!("{s:?}"))
            .collect();
        rendered.push_str(&format!("deny_columns = [{}]\n\n", cols.join(", ")));
    }

    let mut sources = 0usize;
    if let Some(list) = table.get("sources").and_then(|v| v.as_array()) {
        for source in list {
            let Some(source) = source.as_table() else {
                warnings.push("a [[sources]] entry is not a table; skipped".into());
                continue;
            };
            let Some(name) = source.get("name").and_then(|v| v.as_str()) else {
                bail!("a [[sources]] entry has no name");
            };
            rendered.push_str("[[sources]]\n");
            rendered.push_str(&format!("name = {name:?}\n"));
            for key in ["url", "url_env", "engine"] {
                if let Some(value) = source.get(key).and_then(|v| v.as_str()) {
                    rendered.push_str(&format!("{key} = {value:?}\n"));
                }
            }
            if source.get("url").is_none() && source.get("url_env").is_none() {
                warnings.push(format!(
                    "source '{name}' has neither url nor url_env; V2 requires one of them"
                ));
            }
            rendered.push('\n');
            sources += 1;
        }
    } else {
        warnings.push("no [[sources]] table found; V2 falls back to DATABASE_URL or --url".into());
    }

    for (key, flag) in MOVED_TO_FLAGS {
        if table.contains_key(*key) {
            warnings.push(format!(
                "top-level '{key}' is not a V2 TOML key; pass {flag} on the command line instead"
            ));
        }
    }

    for warning in &warnings {
        eprintln!("warning: {warning}");
    }

    if write {
        let out = out.unwrap_or_else(|| Path::new(DEFAULT_OUT));
        std::fs::write(out, &rendered).with_context(|| format!("writing {}", out.display()))?;
        println!(
            "wrote {} ({sources} source(s), {} warning(s)); dry runs never overwrite",
            out.display(),
            warnings.len()
        );
    } else {
        println!("{rendered}");
        println!(
            "# dry run: {} source(s), {} warning(s). Re-run with --write to save.",
            sources,
            warnings.len()
        );
    }
    Ok(0)
}
